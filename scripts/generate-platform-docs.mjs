import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const source = new URL('../docs/operaciones/restaurar-base-local.md', import.meta.url)
const target = new URL('../apps/api/src/modules/platform/application/platform-documentation.generated.ts', import.meta.url)
const content = readFileSync(source, 'utf8')
const output = '// Generated by scripts/generate-platform-docs.mjs. Edit the Markdown source.\n'
  + `export const restorationGuide = ${JSON.stringify(content)}\n`
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    console.error('Documentación desactualizada. Ejecuta pnpm docs:sync.')
    process.exitCode = 1
  }
} else {
  writeFileSync(target, output)
  console.log(`Documentación sincronizada: ${fileURLToPath(target)}`)
}
