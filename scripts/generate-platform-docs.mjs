import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const sources = [
  ['quickStartGuide', '../docs/operaciones/guia-practica.md'],
  ['restorationGuide', '../docs/operaciones/restaurar-base-local.md'],
  ['railwayRecoveryGuide', '../docs/operaciones/recuperar-railway.md'],
]
const target = new URL('../apps/api/src/modules/platform/application/platform-documentation.generated.ts', import.meta.url)
const output = '// Generated by scripts/generate-platform-docs.mjs. Edit the Markdown source.\n'
  + sources.map(([name, relativePath]) => `export const ${name} = ${JSON.stringify(readFileSync(new URL(relativePath, import.meta.url), 'utf8'))}\n`).join('')
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    console.error('Documentación desactualizada. Ejecuta pnpm docs:sync.')
    process.exitCode = 1
  }
} else {
  writeFileSync(target, output)
  console.log(`Documentación sincronizada: ${fileURLToPath(target)}`)
}
